#!/usr/bin/env python3.14
"""Generates src/classifier/pyclasses.rs: Python's own character classes and case mappings.

The classifier port must reproduce Python 3.14's `re` and `str` on Unicode 16.0.0 exactly
(spec/CLASSIFIER.md §6.3). Every table here is read from Python itself, never derived from
the Unicode data by hand:

- regex classes: each code point is tested with `re.fullmatch` on `\\d`, `\\w`, `\\s`,
  `[^\\W\\d_]` and `[^\\W_]`;
- predicates: `str.isupper`, `islower`, `isdigit`, `isdecimal`, `isspace` on the
  one-character string. The titlecase flag is `unicodedata.category(ch) == "Lt"`, the flag
  CPython's `str.isupper()` of a string tests: the one-character `str.istitle()` is not it,
  because it is also true for uppercase letters (`"A".istitle()`). `iscased` is
  `isupper or islower or Lt`, the Unicode Cased property that CPython's `str.title()` uses;
- mappings: `str.lower`, `str.upper` and `str.title` of each code point, where they differ
  from the code point, including the ones with more than one code point.

Surrogates (U+D800 to U+DFFF) are left out: a Rust `char` cannot hold them.

Usage, from embeddings-fundamentals/:
    python3.14 scripts/gen-pyclasses.py > src/classifier/pyclasses.rs
"""

import hashlib
import pathlib
import re
import sys
import unicodedata

UNIDATA = "16.0.0"

if unicodedata.unidata_version != UNIDATA:
    sys.exit(f"needs Unicode {UNIDATA}; this Python has {unicodedata.unidata_version} (use python3.14)")

CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out = []
    for ch in CHARS:
        c = ord(ch)
        if pred(ch):
            if out and out[-1][1] == c - 1:
                out[-1][1] = c
            else:
                out.append([c, c])
    return out


def regex(pattern):
    compiled = re.compile(pattern)
    return lambda ch: compiled.fullmatch(ch) is not None


def rust_str(s):
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7F and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in s) + '"'


def table(name, doc, rs):
    body = ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in rs)
    return f"/// {doc}\n#[rustfmt::skip]\npub static {name}: &[(u32, u32)] = &[{body}];\n"


def mapping(name, doc, fn):
    pairs = [(ord(ch), fn(ch)) for ch in CHARS if fn(ch) != ch]
    body = ", ".join(f"(0x{c:x}, {rust_str(m)})" for c, m in pairs)
    return f"/// {doc}\n#[rustfmt::skip]\npub static {name}: &[(u32, &str)] = &[{body}];\n"


generator = hashlib.sha256(pathlib.Path(__file__).read_bytes()).hexdigest()
python = ".".join(map(str, sys.version_info[:3]))

parts = [
    "//! GENERATED by `scripts/gen-pyclasses.py`; do not edit.\n",
    "//!\n",
    f"//! Python {python}, Unicode {UNIDATA}. Character classes of Python's `re` and `str`, as\n",
    "//! sorted, disjoint, inclusive code-point ranges, and case mappings as sorted\n",
    "//! (code point, result) pairs (spec/CLASSIFIER.md §6.3).\n\n",
    f'/// Python version the tables were read from.\npub const PYTHON_VERSION: &str = "{python}";\n',
    f'/// Unicode version of the tables.\npub const UNIDATA_VERSION: &str = "{UNIDATA}";\n',
    # Split as rustfmt does, so `cargo fmt` leaves the file byte-identical.
    f'/// sha256 of the generator that wrote this file.\npub const GENERATOR_SHA256: &str =\n    "{generator}";\n\n',
    table("RE_DIGIT", r"`\d` of Python's `re`.", ranges(regex(r"\d"))),
    table("RE_WORD", r"`\w` of Python's `re`.", ranges(regex(r"\w"))),
    table("RE_SPACE", r"`\s` of Python's `re`.", ranges(regex(r"\s"))),
    table("RE_LETTER", r"`[^\W\d_]` of Python's `re`.", ranges(regex(r"[^\W\d_]"))),
    table("RE_ALNUM", r"`[^\W_]` of Python's `re`.", ranges(regex(r"[^\W_]"))),
    table("IS_UPPER", "`str.isupper()` of one code point.", ranges(str.isupper)),
    table("IS_LOWER", "`str.islower()` of one code point.", ranges(str.islower)),
    table("IS_TITLE", "Titlecase letters (category Lt): CPython's `Py_UNICODE_ISTITLE`.",
          ranges(lambda ch: unicodedata.category(ch) == "Lt")),
    table("IS_CASED", "Cased: `isupper or islower or Lt` of one code point.",
          ranges(lambda ch: ch.isupper() or ch.islower() or unicodedata.category(ch) == "Lt")),
    table("IS_DIGIT", "`str.isdigit()` of one code point.", ranges(str.isdigit)),
    table("IS_DECIMAL", "`str.isdecimal()` of one code point.", ranges(str.isdecimal)),
    table("IS_SPACE", "`str.isspace()` of one code point.", ranges(str.isspace)),
    mapping("LOWER", "`str.lower()` of each code point it changes.", str.lower),
    mapping("UPPER", "`str.upper()` of each code point it changes.", str.upper),
    mapping("TITLE", "`str.title()` of each code point it changes.", str.title),
]
sys.stdout.write("".join(parts))
