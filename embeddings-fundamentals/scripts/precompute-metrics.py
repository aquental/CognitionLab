#!/usr/bin/env python3
"""Precompute expected retrieval metrics for a BDD fixture, independently of the Rust
evaluator (PRD §5.3).

Input: a TOML file with the hand-derived label of each returned rank per query, and
the frozen relevance-label file. Output (stdout): the same TOML with per-query and
macro-averaged Precision@3, Hit@3, and nDCG@3 appended.

    python3 scripts/precompute-metrics.py tests/fixtures/metrics/text-only.ranks.toml \
        config/evaluation/labels-synthetic-v1.toml > tests/fixtures/metrics/text-only.toml
"""
import math
import sys
import tomllib


def metrics(returned, frozen):
    top = returned[:3]
    precision = sum(1 for g in top if g >= 1) / 3
    hit = 1.0 if any(g >= 1 for g in top) else 0.0
    dcg = sum((2**g - 1) / math.log2(r + 2) for r, g in enumerate(top))
    ideal = sorted(frozen, reverse=True)[:3]
    idcg = sum((2**g - 1) / math.log2(r + 2) for r, g in enumerate(ideal))
    return precision, hit, (dcg / idcg if idcg > 0 else 0.0)


def main():
    ranks_path, labels_path = sys.argv[1], sys.argv[2]
    with open(ranks_path, "rb") as f:
        ranks = tomllib.load(f)
    with open(labels_path, "rb") as f:
        labels = tomllib.load(f)
    raw = open(ranks_path, encoding="utf-8").read().rstrip("\n")
    print(raw)
    print()
    print("# ---- generated by scripts/precompute-metrics.py; do not edit below ----")
    totals = [0.0, 0.0, 0.0]
    for q in ranks["query"]:
        frozen = [l["label"] for l in labels["label"] if l["query"] == q["id"]]
        p, h, n = metrics(q["ranks"], frozen)
        totals = [totals[0] + p, totals[1] + h, totals[2] + n]
        print()
        print("[[expected]]")
        print(f'query = "{q["id"]}"')
        print(f"precision_at_3 = {p!r}")
        print(f"hit_at_3 = {h!r}")
        print(f"ndcg_at_3 = {n!r}")
    count = len(ranks["query"])
    print()
    print("[macro]")
    print(f"precision_at_3 = {totals[0] / count!r}")
    print(f"hit_at_3 = {totals[1] / count!r}")
    print(f"ndcg_at_3 = {totals[2] / count!r}")


if __name__ == "__main__":
    main()
